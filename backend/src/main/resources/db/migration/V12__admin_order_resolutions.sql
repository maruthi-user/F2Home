CREATE TABLE f2home_order_resolutions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES f2home_orders(id),
    admin_id BIGINT NOT NULL,
    admin_name VARCHAR(255) NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE NOT NULL,
    action VARCHAR(32) NOT NULL,
    reason VARCHAR(500) NOT NULL CHECK (length(trim(reason)) > 0),
    previous_status VARCHAR(20) NOT NULL,
    resulting_status VARCHAR(20) NOT NULL,
    previous_cash NUMERIC(12, 2),
    resulting_cash NUMERIC(12, 2)
);

CREATE INDEX idx_f2home_order_resolutions_order ON f2home_order_resolutions (order_id, id);
CREATE UNIQUE INDEX idx_f2home_order_cash_resolution ON f2home_order_resolutions (order_id)
    WHERE action IN ('CONFIRM_FULL_CASH', 'KEEP_RECORDED_CASH');
