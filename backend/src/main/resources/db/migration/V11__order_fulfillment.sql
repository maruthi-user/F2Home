ALTER TABLE f2home_orders
    ADD COLUMN cash_collected NUMERIC(12, 2),
    DROP CONSTRAINT ck_f2home_orders_status,
    DROP CONSTRAINT ck_f2home_orders_payment_status;

ALTER TABLE f2home_orders
    ADD CONSTRAINT ck_f2home_orders_status
        CHECK (status IN ('PLACED', 'CONFIRMED', 'PREPARING', 'OUT_FOR_DELIVERY', 'DELIVERY_FAILED', 'DELIVERED', 'CANCELLED')),
    ADD CONSTRAINT ck_f2home_orders_payment_status
        CHECK (payment_status IN ('PENDING', 'PAID', 'FAILED', 'REFUNDED', 'COLLECTION_EXCEPTION')),
    ADD CONSTRAINT ck_f2home_orders_cash_collected CHECK (cash_collected >= 0);

CREATE TABLE f2home_order_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES f2home_orders(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    note VARCHAR(300)
);

CREATE INDEX idx_f2home_order_events_order_id ON f2home_order_events (order_id, id);
