CREATE TABLE f2home_saved_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES f2home_users(id) ON DELETE CASCADE,
    name VARCHAR(60) NOT NULL,
    address JSONB NOT NULL
);
CREATE INDEX idx_f2home_saved_addresses_customer ON f2home_saved_addresses (customer_id, id DESC);
