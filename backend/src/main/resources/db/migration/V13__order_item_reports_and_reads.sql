CREATE TABLE f2home_item_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES f2home_orders(id),
    item_id BIGINT NOT NULL REFERENCES f2home_order_items(id),
    item_name VARCHAR(150) NOT NULL,
    kind VARCHAR(20) NOT NULL CHECK (kind IN ('MISSING', 'DAMAGED')),
    details VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    resolved_at TIMESTAMP WITH TIME ZONE,
    admin_id BIGINT,
    admin_name VARCHAR(255),
    resolution VARCHAR(500)
);
CREATE INDEX idx_f2home_item_reports_order ON f2home_item_reports (order_id);
CREATE UNIQUE INDEX uq_f2home_open_item_report ON f2home_item_reports (item_id) WHERE resolved_at IS NULL;

ALTER TABLE f2home_order_events ADD COLUMN customer_read BOOLEAN NOT NULL DEFAULT FALSE;
